def ensure_builtin_personas():
    with state_lock():
        registry = root() / "data" / "personas.json"
        marker = root() / "data" / "installed_presets.json"
        installed = read_json(marker, [])
        if "angelina" in installed:
            return
        personas = read_json(registry, [])
        if not any(p.get("name") == "angelina" for p in personas):
            directory = persona_dir("angelina")
            settings = directory / "settings.json"
            if not settings.exists():
                write_json(settings, ANGELINA_SETTINGS)
            personas.append(ANGELINA)
            write_json(registry, personas)
        installed.append("angelina")
        write_json(marker, installed)
